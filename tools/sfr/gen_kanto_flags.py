#!/usr/bin/env python3
"""Super Fire Red: generates include/constants/flags_kanto.h

The Emerald build normally stubs every FRLG flag name to 0. To have Kanto and Hoenn
in the same game, each FRLG-only flag gets its own ID in a block placed after the
Emerald flags. Flags that both games define for real (system flags, badges, tickets,
Mystery Gift...) keep the Emerald value and are shared by both regions.

Usage (from the repo root): python3 tools/sfr/gen_kanto_flags.py
Needs a host gcc. Reads include/constants/flags.h and flags_frlg.h.
"""
import os, re, subprocess, sys, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(ROOT)

FRLG_FLAGS = 'include/constants/flags_frlg.h'
OUT = 'include/constants/flags_kanto.h'

# Layout of the Kanto block (values are offsets from KANTO_FLAGS_START)
FRLG_STORY_START, FRLG_STORY_END = 0x020, 0x4FF      # story, hide, item, hidden item, daily
FRLG_SYS_START, FRLG_SYS_END = 0x800, 0x8FF          # FRLG system flags
SYS_OFFSET = (FRLG_STORY_END - FRLG_STORY_START + 1)  # 0x4E0
KANTO_TRAINER_OFFSET = SYS_OFFSET + (FRLG_SYS_END - FRLG_SYS_START + 1)  # 0x5E0

# Names that collide with Emerald but mean something different in Kanto.
RENAMED = {
    'FLAG_HIDDEN_ITEM_VICTORY_ROAD_1F_ULTRA_BALL': 'FLAG_HIDDEN_ITEM_KANTO_VICTORY_ROAD_1F_ULTRA_BALL',
}

SKIP = re.compile(r'^(SYS_FLAGS|DAILY_FLAGS_\w+|NUM_\w+|TRAINER_FLAGS_\w+|FLAG_HIDDEN_ITEMS_START|'
                  r'SPECIAL_FLAGS_\w+|FLAGS_COUNT|STORY_FLAGS_START|TEMP_FLAGS_\w+|GUARD_\w+)$')


def names_in(path):
    out = []
    for line in open(path):
        m = re.match(r'\s*#define\s+(\w+)\s+\S', line)
        if m and m.group(1) not in out:
            out.append(m.group(1))
    return out


def evaluate(names, game_define, extra_include=None):
    src = ['#include <stdio.h>', '#include "constants/global.h"', '#include "constants/opponents.h"']
    src.append(extra_include or '#include "constants/flags.h"')
    src.append('int main(void){')
    for n in names:
        src.append(f'#ifdef {n}\nprintf("{n} %ld\\n", (long)({n}));\n#endif')
    src.append('return 0;}')
    with tempfile.TemporaryDirectory() as d:
        c, exe = os.path.join(d, 'p.c'), os.path.join(d, 'p')
        open(c, 'w').write('\n'.join(src))
        subprocess.run(['gcc', f'-D{game_define}', '-DMODERN=1', '-DTESTING=0', '-DSFR_GEN_FLAGS=1', '-w',
                        '-iquote', 'include', c, '-o', exe], check=True)
        res = subprocess.run([exe], check=True, capture_output=True, text=True).stdout
    return {l.split()[0]: int(l.split()[1]) for l in res.splitlines()}


def main():
    frlg_names = [n for n in names_in(FRLG_FLAGS) if not SKIP.match(n)]
    fr = evaluate(frlg_names, 'FIRERED')
    em = evaluate(frlg_names + ['DAILY_FLAGS_END'], 'EMERALD')

    base = em['DAILY_FLAGS_END'] + 1   # first flag after the Emerald ones
    lines = []
    allocated = 0
    for name in frlg_names:
        if SKIP.match(name) or name not in fr:
            continue
        value = fr[name]
        if value == 0:
            continue                      # FRLG stub of an Emerald name
        if em.get(name, 0) != 0 and name not in RENAMED:
            continue                      # real in both: shared, Emerald value is used
        out_name = RENAMED.get(name, name)
        if value < 0x20:
            expr = f'{value:#06x}'        # temp flags are the same range in both games
        elif FRLG_STORY_START <= value <= FRLG_STORY_END:
            expr = f'{base + value - FRLG_STORY_START:#06x}'
        elif FRLG_SYS_START <= value <= FRLG_SYS_END:
            expr = f'{base + SYS_OFFSET + value - FRLG_SYS_START:#06x}'
        elif value >= 0x4000:
            print(f'warning: FRLG-only special flag {name} ({value:#x}) not handled', file=sys.stderr)
            continue
        else:
            print(f'warning: {name} ({value:#x}) outside known FRLG ranges', file=sys.stderr)
            continue
        lines.append(f'#define {out_name:<70} {expr} // FRLG {value:#05x}')
        allocated += 1

    header = f'''#ifndef GUARD_CONSTANTS_FLAGS_KANTO_H
#define GUARD_CONSTANTS_FLAGS_KANTO_H

// GENERATED by tools/sfr/gen_kanto_flags.py - do not edit by hand.
// Super Fire Red: FRLG-only flags, moved to their own block after the Emerald flags.

// Plain numbers on purpose: FRLG scripts pass flags to macros without commas.
#define KANTO_FLAGS_START           {base:#06x} // DAILY_FLAGS_END + 1
#define KANTO_SYS_FLAGS_START       {base + SYS_OFFSET:#06x}
#define KANTO_TRAINER_FLAGS_START   {base + KANTO_TRAINER_OFFSET:#06x}
#define KANTO_TRAINER_FLAGS_END     (KANTO_TRAINER_FLAGS_START + MAX_TRAINERS_COUNT_FRLG - 1)
#define KANTO_FLAGS_END             KANTO_TRAINER_FLAGS_END

'''
    open(OUT, 'w').write(header + '\n'.join(lines) + '\n\n#endif // GUARD_CONSTANTS_FLAGS_KANTO_H\n')
    print(f'{OUT}: {allocated} Kanto flags')


if __name__ == '__main__':
    main()
