#!/usr/bin/env python3
"""Super Fire Red: generates include/constants/vars_kanto.h

Same idea as gen_kanto_flags.py: every FRLG-only var gets its own ID after the
Emerald vars (0x4100 onwards). Vars that both games define for real keep the
Emerald value and are shared.

Usage (from the repo root): python3 tools/sfr/gen_kanto_vars.py
"""
import os, re, subprocess, tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(ROOT)
OUT = 'include/constants/vars_kanto.h'
SKIP = re.compile(r'^(VARS_\w+|TEMP_VARS_\w+|NUM_\w+|SPECIAL_VARS_\w+|GUARD_\w+|VAR_0x[0-9A-Fa-f]+|VAR_TEMP_\w+|VAR_OBJ_GFX_ID_\w)$')


def names_in(path):
    out = []
    for line in open(path):
        m = re.match(r'\s*#define\s+(\w+)\s+\S', line)
        if m and m.group(1) not in out:
            out.append(m.group(1))
    return out


def evaluate(names, game_define):
    src = ['#include <stdio.h>', '#include "constants/global.h"', '#include "constants/vars.h"', 'int main(void){']
    src += [f'#ifdef {n}\nprintf("{n} %ld\\n", (long)({n}));\n#endif' for n in names]
    src.append('return 0;}')
    with tempfile.TemporaryDirectory() as d:
        c, exe = os.path.join(d, 'p.c'), os.path.join(d, 'p')
        open(c, 'w').write('\n'.join(src))
        subprocess.run(['gcc', f'-D{game_define}', '-DMODERN=1', '-DTESTING=0', '-DSFR_GEN_VARS=1', '-w',
                        '-iquote', 'include', c, '-o', exe], check=True)
        res = subprocess.run([exe], check=True, capture_output=True, text=True).stdout
    return {l.split()[0]: int(l.split()[1]) for l in res.splitlines()}


def main():
    names = names_in('include/constants/vars_frlg.h')
    fr, em = evaluate(names, 'FIRERED'), evaluate(names, 'EMERALD')
    lines = []
    for n in names:
        if SKIP.match(n) or fr.get(n, 0) == 0:
            continue
        if em.get(n, 0) != 0:
            continue  # shared
        lines.append(f'#define {n:<70} {0x4100 + len(lines):#06x} // FRLG {fr[n]:#06x}')
    out = f'''#ifndef GUARD_CONSTANTS_VARS_KANTO_H
#define GUARD_CONSTANTS_VARS_KANTO_H

// GENERATED by tools/sfr/gen_kanto_vars.py - do not edit by hand.
// Super Fire Red: FRLG-only vars, placed after the Emerald vars.

#define KANTO_VARS_START 0x4100
#define KANTO_VARS_COUNT {len(lines)}
#define KANTO_VARS_END   (KANTO_VARS_START + KANTO_VARS_COUNT - 1)

''' + '\n'.join(lines) + '\n\n#endif // GUARD_CONSTANTS_VARS_KANTO_H\n'
    open(OUT, 'w').write(out)
    print(f'{OUT}: {len(lines)} Kanto vars')


if __name__ == '__main__':
    main()
